import sanitizeHtml from "sanitize-html";

const ALLOWED_TAGS = [
  "a",
  "article",
  "aside",
  "blockquote",
  "br",
  "caption",
  "code",
  "col",
  "colgroup",
  "dd",
  "del",
  "details",
  "desc",
  "div",
  "dl",
  "dt",
  "em",
  "figcaption",
  "figure",
  "h1",
  "h2",
  "h3",
  "h4",
  "hr",
  "img",
  "li",
  "ol",
  "p",
  "pre",
  "s",
  "section",
  "small",
  "span",
  "strong",
  "sub",
  "summary",
  "sup",
  "table",
  "tbody",
  "td",
  "th",
  "thead",
  "tr",
  "ul",
  "svg",
  "g",
  "path",
  "rect",
  "circle",
  "ellipse",
  "line",
  "polyline",
  "polygon",
  "text",
  "tspan",
  "title",
  "defs",
  "marker",
];

const ALLOWED_ATTRIBUTES = {
  "*": ["id", "class", "title", "aria-*", "data-*"],
  a: ["href", "target", "rel"],
  img: ["src", "alt", "width", "height", "loading", "decoding"],
  td: ["colspan", "rowspan", "align"],
  th: ["colspan", "rowspan", "scope", "align"],
  ol: ["start"],
  svg: ["viewbox", "xmlns", "width", "height", "role", "aria-label"],
  path: [
    "d",
    "fill",
    "stroke",
    "stroke-width",
    "stroke-linecap",
    "stroke-linejoin",
    "marker-end",
  ],
  rect: ["x", "y", "width", "height", "rx", "fill", "stroke", "stroke-width"],
  circle: ["cx", "cy", "r", "fill", "stroke", "stroke-width"],
  ellipse: ["cx", "cy", "rx", "ry", "fill", "stroke", "stroke-width"],
  line: ["x1", "y1", "x2", "y2", "stroke", "stroke-width", "stroke-dasharray"],
  polyline: ["points", "fill", "stroke", "stroke-width"],
  polygon: ["points", "fill", "stroke", "stroke-width"],
  text: ["x", "y", "fill", "text-anchor", "dominant-baseline"],
  tspan: ["x", "y", "dx", "dy"],
  marker: ["id", "markerwidth", "markerheight", "refx", "refy", "orient"],
};

export function sanitizeLegacyHtml(value: string): string {
  return sanitizeHtml(value, {
    allowedTags: ALLOWED_TAGS,
    allowedAttributes: ALLOWED_ATTRIBUTES,
    allowedSchemes: ["http", "https", "mailto"],
    allowedSchemesAppliedToAttributes: ["href", "src", "cite"],
    allowProtocolRelative: false,
    disallowedTagsMode: "discard",
  });
}
